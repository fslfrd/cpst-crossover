"""Plain-text and Markdown reports. RESULTS.md is generated from this."""

from __future__ import annotations

from math import inf, isinf

from .data import Dataset
from .model import crossover_estimate, inference_cpst, lower_envelope


def _usd(x: float) -> str:
    return "unbounded" if isinf(x) else f"${x:,.2f}"


def _minutes(L: float, hourly: float) -> str:
    if isinf(L):
        return "unbounded"
    m = L / hourly * 60
    return f"{m * 60:.0f} sec" if m < 1 else f"{m:.1f} min"


def build_report(ds: Dataset, l_max: float = 20.0, hourly: float = 80.0) -> str:
    meta = ds.meta
    hw = ds.pass_rate_halfwidth
    out: list[str] = []
    w = out.append

    w("# Results")
    w("")
    w("Generated by `python -m cpst report`. Do not edit by hand.")
    w("")
    w(f"Source: [{meta['title']}]({meta['url']}), {meta['publisher']}, "
      f"published {meta['published']}, figures checked {meta['retrieved']}. "
      f"{meta['benchmark']}, {meta['trials_per_task']} trials per task, "
      f"{meta['total_runs']:,} runs. Grading: {meta['grading']}")
    w("")
    w(f"Human time conversions assume a loaded labor cost of ${hourly:.0f} an hour. "
      "Change it with `--hourly`.")
    w("")

    # 1. Cross-check
    w("## 1. Cross-check against published CPST")
    w("")
    w("Derived CPST is published cost per attempt divided by published pass rate. "
      "Pass rates are published rounded to whole points, so small differences are expected.")
    w("")
    w("| Model | Pass rate | $/attempt | Derived CPST | Published CPST |")
    w("|---|---:|---:|---:|---:|")
    for m in sorted(ds.models, key=inference_cpst):
        pub = f"${m.published_cpst:.3f}" if m.published_cpst is not None else "n/a"
        w(f"| {m.name} | {m.pass_rate:.0%} | ${m.cost_per_attempt:.3f} | "
          f"${inference_cpst(m):.3f} | {pub} |")
    w("")

    # 2. Envelope
    w(f"## 2. Cheapest model by repair cost ($0 to ${l_max:.0f} per failure)")
    w("")
    w("Loaded CPST = cost per attempt + failure rate x repair cost, under the "
      "repair model in METHODOLOGY.md. Point estimates.")
    w("")
    env = lower_envelope(ds.models, l_max)
    w("| Repair cost per failure | Human time | Cheapest model |")
    w("|---|---|---|")
    for r in env:
        span = f"{_usd(r.start)} to {_usd(r.end)}"
        time = f"{_minutes(r.start, hourly)} to {_minutes(r.end, hourly)}"
        w(f"| {span} | {time} | {r.model.name} |")
    w("")

    # 3. Crossovers between successive envelope models, plus the headline pair
    w("## 3. Crossovers, with uncertainty")
    w("")
    w(f"Ranges propagate the publisher's approximate ±{hw * 100:.0f} point 95% interval on "
      f"each pass rate, combined as ±{hw * 100 * 2 ** 0.5:.1f} points on the gap "
      "(conservative; see METHODOLOGY.md). A crossover is **resolved** only if the gap's "
      "range excludes zero. An unresolved crossover means the data cannot tell the two "
      "models' reliability apart.")
    w("")
    pairs = []
    for a, b in zip(env, env[1:]):
        pairs.append((a.model, b.model))
    first, last = env[0].model, env[-1].model
    if (first, last) not in pairs and first is not last:
        pairs.append((first, last))

    w("| Cheaper model | More reliable model | Reliability gap | Crossover | Range | Human time (point) | Resolved |")
    w("|---|---|---:|---:|---|---|---|")
    for a, b in pairs:
        e = crossover_estimate(a, b, hw)
        if e is None:
            continue
        w(f"| {e.cheaper.name} | {e.more_reliable.name} | "
          f"{e.gap * 100:.0f} ± {e.gap_halfwidth * 100:.1f} pts | {_usd(e.point)} | "
          f"{_usd(e.low)} to {_usd(e.high)} | {_minutes(e.point, hourly)} | "
          f"{'yes' if e.resolved else 'no'} |")
    w("")

    # 4. All tradeoff pairs, for completeness
    w("## 4. Every pair with a cost-reliability tradeoff")
    w("")
    w("Pairs where one model is both cheaper and more reliable are omitted: there is no "
      "crossover, the dominant model is always cheaper.")
    w("")
    w("| Cheaper model | More reliable model | Gap | Crossover | Resolved |")
    w("|---|---|---:|---:|---|")
    rows = []
    ms = ds.models
    for i in range(len(ms)):
        for j in range(i + 1, len(ms)):
            e = crossover_estimate(ms[i], ms[j], hw)
            if e is not None:
                rows.append(e)
    for e in sorted(rows, key=lambda e: e.point):
        w(f"| {e.cheaper.name} | {e.more_reliable.name} | {e.gap * 100:.0f} pts | "
          f"{_usd(e.point)} | {'yes' if e.resolved else 'no'} |")
    w("")

    w("## Caveats from the source")
    w("")
    for c in meta.get("caveats", []):
        w(f"- {c}")
    w(f"- Cost basis: {meta['cost_basis']}")
    w("")
    return "\n".join(out)
