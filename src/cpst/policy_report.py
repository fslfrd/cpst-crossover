"""POLICIES.md: retry and escalation policies priced with human repair cost."""

from __future__ import annotations

from math import isinf
from pathlib import Path

from .data import Dataset, model_keys
from .policies import (
    Policy,
    Runs,
    bootstrap_threshold,
    envelope,
    evaluate,
    single,
)

# Repair costs shown in the policy table, as seconds of human time at the hourly rate.
SHOW_SECONDS = (30, 60, 300)


def default_policies(keys: dict[str, str]) -> list[Policy]:
    """The fixed policy set. Chosen to cover the single-model results (the cheapest
    models, the most reliable ones) plus the escalation ladder Arize published.
    No search over policies is run, so the results carry no selection effect."""
    oss, fl, k26, g55, k3 = (keys[n] for n in
                             ("gpt-oss-120b", "gemini-3.1-flash-lite", "Kimi K2.6", "GPT-5.5", "Kimi K3"))
    out = [single(m, k) for m in (oss, fl, g55, k3) for k in (1, 2, 3)]
    out += [
        Policy("arize-ladder", ((oss, 1), (fl, 1), (k26, 1), (g55, 1))),
        Policy("oss-then-g55", ((oss, 1), (g55, 1))),
        Policy("oss2-then-g55", ((oss, 2), (g55, 1))),
        Policy("fl-then-g55", ((fl, 1), (g55, 1))),
    ]
    return out


def key_comparisons(keys: dict[str, str]) -> list[tuple[str, Policy, Policy]]:
    oss, fl, k26, g55 = (keys[n] for n in ("gpt-oss-120b", "gemini-3.1-flash-lite", "Kimi K2.6", "GPT-5.5"))
    ladder = Policy("arize-ladder", ((oss, 1), (fl, 1), (k26, 1), (g55, 1)))
    return [
        ("Single models: flash-lite vs GPT-5.5", single(fl), single(g55)),
        ("Single models: gpt-oss-120b vs GPT-5.5", single(oss), single(g55)),
        ("Retry the cheap model vs pay for GPT-5.5", single(oss, 3), single(g55)),
        ("Retry flash-lite vs the escalation ladder", single(fl, 3), ladder),
        ("GPT-5.5 alone vs the escalation ladder", single(g55), ladder),
    ]


def _usd(x: float) -> str:
    return "unbounded" if isinf(x) else f"${x:,.2f}"


def _time(L: float, hourly: float) -> str:
    if isinf(L):
        return "unbounded"
    s = L / hourly * 3600
    return f"{s:.0f} sec" if s < 90 else f"{s / 60:.1f} min"


def build_policy_report(ds: Dataset, runs: Runs, runs_path: Path, hourly: float = 80.0,
                        l_max: float = 20.0, replicates: int = 2000) -> str:
    keys = model_keys(ds)
    short = {v: k for k, v in keys.items()}
    short["goog-gemini-3.1-flash-lite"] = "flash-lite"
    meta, rmeta = ds.meta, ds.meta["runs"]
    pols = default_policies(keys)
    res = {p.name: evaluate(p, runs) for p in pols}
    out: list[str] = []
    w = out.append

    w("# Retry and escalation policies")
    w("")
    w("Generated by `python -m cpst policies`. Do not edit by hand.")
    w("")
    w("What does a task cost when a model can retry, hand off to a stronger model, and finally "
      "hand off to a person? Computed from the per-run results behind "
      f"[{meta['title']}]({meta['url']}), at commit `{rmeta['commit'][:12]}` of "
      f"[{rmeta['repo'].removeprefix('https://github.com/')}]({rmeta['repo']}). "
      "Assumptions are in METHODOLOGY.md; the main one is that a failure is always detected, "
      "so a retry or escalation happens only after a real failure.")
    w("")
    w(f"Human time assumes ${hourly:.0f} an hour loaded. Uncertainty is a paired two-stage bootstrap "
      f"({replicates:,} replicates: tasks, then trials within each task).")
    w("")

    # Reproduction checks
    w("## 1. Reproduction checks")
    w("")
    w("The per-run file must reproduce Arize's published figures before anything is built on it.")
    w("")
    w("| Model | Pass rate (runs) | Published | $/attempt (runs) | Published |")
    w("|---|---:|---:|---:|---:|")
    for m in ds.models:
        r = evaluate(single(keys[m.name]), runs)
        w(f"| {m.name} | {1 - r.human_share:.1%} | {m.pass_rate:.0%} | ${r.machine_cost:.4f} | "
          f"${m.cost_per_attempt:.3f} |")
    lad = res["arize-ladder"]
    w("")
    w(f"Arize's escalation ladder, inference only: **${lad.inference_cpst:.3f}** per task the models "
      "complete, against **$0.525** published. Small differences come from how retries are sampled.")
    w("")

    # Policy table
    w("## 2. Every policy")
    w("")
    hdr = " | ".join(f"Loaded at {s} sec" if s < 90 else f"Loaded at {s // 60} min" for s in SHOW_SECONDS)
    w(f"| Policy | API cost per task | Tasks left for a person | Inference-only CPST | {hdr} |")
    w("|---|---:|---:|---:|" + "---:|" * len(SHOW_SECONDS))
    for r in sorted(res.values(), key=lambda r: r.machine_cost):
        loaded = " | ".join(f"${r.loaded(hourly * s / 3600):.3f}" for s in SHOW_SECONDS)
        w(f"| {r.policy.label(short)} | ${r.machine_cost:.3f} | {r.human_share:.1%} | "
          f"${r.inference_cpst:.3f} | {loaded} |")
    w("")
    unsolved = [t for t in runs.tasks if all(runs.cells[m][t].p == 0 for m in runs.models)]
    attempts = sum(len(runs.cells[m][runs.tasks[0]].passes) for m in runs.models)
    w(f"{len(unsolved)} of {len(runs.tasks)} tasks ({len(unsolved) / len(runs.tasks):.1%}) were never solved "
      f"by any model in {attempts} attempts each ({', '.join(f'`{t}`' for t in unsolved)}). "
      "Every policy sends those to a person.")
    w("")

    # Envelope
    w(f"## 3. Cheapest policy by repair cost ($0 to ${l_max:.0f} per failure)")
    w("")
    w("| Repair cost per failure | Human time | Cheapest policy |")
    w("|---|---|---|")
    for a, b, r in envelope(list(res.values()), l_max):
        w(f"| {_usd(a)} to {_usd(b)} | {_time(a, hourly)} to {_time(b, hourly)} | {r.policy.label(short)} |")
    w("")

    # Key comparisons
    w("## 4. Key comparisons, with uncertainty")
    w("")
    w("Threshold: the repair cost above which the second policy is cheaper. A threshold of $0.00 "
      "means the second policy is cheaper at every repair cost. \"Second always cheaper\" is the "
      "share of bootstrap replicates in which that holds.")
    w("")
    w("| Comparison | First | Second | Threshold | 95% range | Human time | Second always cheaper |")
    w("|---|---|---|---:|---|---|---:|")
    for title, a, b in key_comparisons(keys):
        e = bootstrap_threshold(a, b, runs, n=replicates)
        w(f"| {title} | {a.label(short)} | {b.label(short)} | {_usd(e.point)} | "
          f"{_usd(e.low)} to {_usd(e.high)} | {_time(e.point, hourly)} | {e.share_b_dominates:.0%} |")
    w("")

    # Sensitivity
    w("## 5. Sensitivity: drawing distinct trials")
    w("")
    w("Retries above draw trials with replacement. Drawing distinct observed trials instead "
      "makes retries look somewhat better, because a failed trial is not drawn again.")
    w("")
    w("| Policy | Tasks left for a person (default) | Distinct trials |")
    w("|---|---:|---:|")
    for name in ("goog-gemini-3.1-flash-lite x3", "fw-gpt-oss-120b x3", "arize-ladder", "oai-gpt-5.5 x1"):
        p = next(p for p in pols if p.name == name)
        alt = evaluate(p, runs, replacement=False)
        w(f"| {p.label(short)} | {res[name].human_share:.1%} | {alt.human_share:.1%} |")
    w("")
    return "\n".join(out)
